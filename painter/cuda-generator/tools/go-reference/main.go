// ---- copied from internal/engine/engine.go

func snapToValidRX(v float32) float32 {
	k := float32(math.Round(float64(v) * (100.0 / 63.0)))
	if k < 1 {
		k = 1
	}
	return k * (63.0 / 100.0)
}

func maxInt(a, b int) int {
	if a > b {
		return a
	}
	return b
}

func scaleCompatibilityPenalty(rx0, ry0 float32, acceptedShapes int) float32 {
	if rx0 < 0 || ry0 < 0 {
		return 0
	}
	rx := float64(maxInt(1, int(math.Round(float64(rx0)))))
	ry := float64(maxInt(1, int(math.Round(float64(ry0)))))
	span := math.Max(rx, ry)
	if acceptedShapes < 8 && span >= 96 {
		return float32(span * span * 0.1)
	}
	if span >= 96 {
		return float32(span * 0.05)
	}
	return 0
}

func f32ToByte(v float32) uint8 {
	if v < 0 {
		v = 0
	}
	if v > 1 {
		v = 1
	}
	return uint8(math.Round(float64(v * 255)))
}

func quantAngle(theta float32) int {
	angle := int(math.Round(float64(theta))) % 360
	if angle < 0 {
		angle += 360
	}
	if angle == 0 && theta > 359.5 {
		angle = 360
	}
	return angle
}

func mutationSteps(width, height int) (move, radius float32) {
	diag := math.Sqrt(float64(width*width) + float64(height*height))
	move = float32(math.Max(2.0, diag*0.012))
	radius = float32(math.Max(2.0, diag*0.010))
	return move, radius
}

func normalizeScore(totalError, denom float64) float64 {
	if denom <= 0 {
		return 0
	}
	value := totalError / denom
	if value < 0 {
		value = 0
	}
	return math.Round(value*1_000_000) / 1_000_000
}

func clampInt(v, minV, maxV int) int {
	if v < minV {
		return minV
	}
	if v > maxV {
		return maxV
	}
	return v
}

// quantizeCandidate's geometry part.
func quantizeXY(x float32, size int) float32 {
	return float32(clampInt(int(math.Round(float64(x))), 0, maxInt(0, size-1)))
}

// ---- copied from internal/imageutil/image.go

type prepared struct {
	w, h   int
	target []float32
	mask   []uint8
	transp bool
	bg     [4]uint8
}

func resizeToMax(src image.Image, maxResolution int) image.Image {
	if maxResolution <= 0 {
		return src
	}
	bounds := src.Bounds()
	w := bounds.Dx()
	h := bounds.Dy()
	maxDim := w
	if h > maxDim {
		maxDim = h
	}
	if maxDim <= maxResolution {
		return src
	}
	scale := float64(maxResolution) / float64(maxDim)
	nw := int(math.Round(float64(w) * scale))
	nh := int(math.Round(float64(h) * scale))
	if nw < 1 {
		nw = 1
	}
	if nh < 1 {
		nh = 1
	}
	dst := image.NewRGBA(image.Rect(0, 0, nw, nh))
	draw.CatmullRom.Scale(dst, dst.Bounds(), src, bounds, draw.Over, nil)
	return dst
}

func prepare(src image.Image, maxResolution int) prepared {
	scaled := resizeToMax(src, maxResolution)
	b := scaled.Bounds()
	w, h := b.Dx(), b.Dy()
	p := prepared{w: w, h: h, target: make([]float32, w*h*4), mask: make([]uint8, w*h)}
	var sumR, sumG, sumB, sumA, n float64
	for y := 0; y < h; y++ {
		for x := 0; x < w; x++ {
			r16, g16, b16, a16 := scaled.At(b.Min.X+x, b.Min.Y+y).RGBA()
			r := float32(r16) / 65535.0
			g := float32(g16) / 65535.0
			bb := float32(b16) / 65535.0
			a := float32(a16) / 65535.0
			if a > 0 && a < 1 {
				r = float32(math.Min(float64(r/a), 1))
				g = float32(math.Min(float64(g/a), 1))
				bb = float32(math.Min(float64(bb/a), 1))
			}
			i := (y*w + x) * 4
			p.target[i], p.target[i+1], p.target[i+2], p.target[i+3] = r, g, bb, a
			if a > 0.001 {
				p.mask[y*w+x] = 1
				sumR += float64(r)
				sumG += float64(g)
				sumB += float64(bb)
				sumA += float64(a)
				n++
			} else {
				p.transp = true
			}
		}
	}
	c := func(v float64) uint8 { return uint8(math.Max(0, math.Min(255, v))) }
	p.bg = [4]uint8{0, 0, 0, 255}
	if n > 0 {
		p.bg = [4]uint8{c(sumR / n * 255), c(sumG / n * 255), c(sumB / n * 255), c(sumA / n * 255)}
	}
	if p.transp {
		p.bg[3] = 0
	}
	return p
}

// ---- output

func f(v float32) string { return fmt.Sprintf("%.17g", float64(v)) }

func main() {
	if len(os.Args) < 2 {
		fmt.Println("usage: go run . <tests-dir>")
		os.Exit(1)
	}
	dir := os.Args[1]
	rng := rand.New(rand.NewSource(1))
	var b strings.Builder
	b.WriteString("// Generated by tools/go-reference. Do not edit.\n")

	b.WriteString("static const float kSnapCases[][2] = {\n")
	for _, v := range []float32{-3, 0, 0.1, 0.31, 0.315, 0.63, 0.945, 1, 1.26, 2, 12.6, 99.99, 500.123} {
		fmt.Fprintf(&b, "    {%s, %s},\n", f(v), f(snapToValidRX(v)))
	}
	for i := 0; i < 200; i++ {
		v := rng.Float32() * 800
		fmt.Fprintf(&b, "    {%s, %s},\n", f(v), f(snapToValidRX(v)))
	}
	b.WriteString("};\n")

	b.WriteString("static const struct { float rx, ry; int accepted; float out; } kPenaltyCases[] = {\n")
	for i := 0; i < 200; i++ {
		rx := rng.Float32()*200 - 5
		ry := rng.Float32() * 200
		if i%5 == 0 {
			rx = 95.5 + rng.Float32()
		}
		acc := rng.Intn(20)
		fmt.Fprintf(&b, "    {%s, %s, %d, %s},\n", f(rx), f(ry), acc, f(scaleCompatibilityPenalty(rx, ry, acc)))
	}
	b.WriteString("};\n")

	b.WriteString("static const struct { float in; int out; } kByteCases[] = {\n")
	for _, v := range []float32{-1, 0, 0.5 / 255, 1.5 / 255, 0.5, 0.998, 1, 2} {
		fmt.Fprintf(&b, "    {%s, %d},\n", f(v), f32ToByte(v))
	}
	for i := 0; i < 100; i++ {
		v := rng.Float32()
		fmt.Fprintf(&b, "    {%s, %d},\n", f(v), f32ToByte(v))
	}
	b.WriteString("};\n")

	b.WriteString("static const struct { float in; int out; } kAngleCases[] = {\n")
	for _, v := range []float32{0, 0.4, 0.5, 359.4, 359.5, 359.6, 359.99, 360, -0.4, -0.6, 180.5, 719.6} {
		fmt.Fprintf(&b, "    {%s, %d},\n", f(v), quantAngle(v))
	}
	b.WriteString("};\n")

	b.WriteString("static const struct { float in; int size; float out; } kQuantXYCases[] = {\n")
	for _, c := range []struct {
		v    float32
		size int
	}{{-0.6, 100}, {0.49, 100}, {0.5, 100}, {98.5, 100}, {99.4, 100}, {150, 100}, {3.5, 1}} {
		fmt.Fprintf(&b, "    {%s, %d, %s},\n", f(c.v), c.size, f(quantizeXY(c.v, c.size)))
	}
	b.WriteString("};\n")

	b.WriteString("static const struct { int w, h; float move, radius; } kStepCases[] = {\n")
	for _, c := range [][2]int{{10, 10}, {1200, 800}, {2000, 1333}, {3000, 3000}} {
		m, r := mutationSteps(c[0], c[1])
		fmt.Fprintf(&b, "    {%d, %d, %s, %s},\n", c[0], c[1], f(m), f(r))
	}
	b.WriteString("};\n")

	b.WriteString("static const struct { double total, denom, out; } kNormCases[] = {\n")
	for i := 0; i < 20; i++ {
		t := rng.Float64() * 1e6
		d := rng.Float64() * 4e6
		fmt.Fprintf(&b, "    {%.17g, %.17g, %.17g},\n", t, d, normalizeScore(t, d))
	}
	b.WriteString("};\n")

	b.WriteString("static const struct { double v; const char* text; } kJsonFloatCases[] = {\n")
	vals := []float64{0, 1, -1, 1200, 0.5, 0.1, 1.0 / 3, 12.6, float64(float32(12.6)), float64(snapToValidRX(7)),
		1e-6, 9.99e-7, 1.2e-7, 1e20, 1e21, 123456789.125, 0.000012, 3.402823466e+38, 2.5e-300}
	for i := 0; i < 20; i++ {
		vals = append(vals, float64(rng.Float32()*1000))
	}
	for _, v := range vals {
		j, _ := json.Marshal(v)
		fmt.Fprintf(&b, "    {%.17g, \"%s\"},\n", v, j)
	}
	b.WriteString("};\n")

	if err := os.WriteFile(filepath.Join(dir, "go_reference.inc"), []byte(b.String()), 0o644); err != nil {
		panic(err)
	}

	// A small test picture with every kind of alpha, saved as a PNG.
	src := image.NewNRGBA(image.Rect(0, 0, 97, 61))
	for y := 0; y < 61; y++ {
		for x := 0; x < 97; x++ {
			a := uint8(255)
			if x > 70 {
				a = 0
			} else if x > 60 {
				a = uint8((70 - x) * 25)
			} else if y < 5 {
				a = uint8(40 + y*30)
			}
			src.SetNRGBA(x, y, color.NRGBA{uint8(x * 255 / 96), uint8(y * 4), uint8((x * y) % 256), a})
		}
	}
	var pngBuf bytes.Buffer
	if err := png.Encode(&pngBuf, src); err != nil {
		panic(err)
	}
	dataDir := filepath.Join(dir, "data")
	os.MkdirAll(dataDir, 0o755)
	if err := os.WriteFile(filepath.Join(dataDir, "alpha_test.png"), pngBuf.Bytes(), 0o644); err != nil {
		panic(err)
	}
	decoded, _, err := image.Decode(bytes.NewReader(pngBuf.Bytes()))
	if err != nil {
		panic(err)
	}
	for _, maxRes := range []int{0, 40, 64} {
		p := prepare(decoded, maxRes)
		var out bytes.Buffer
		hdr := []int32{int32(p.w), int32(p.h), boolInt(p.transp), int32(p.bg[0]), int32(p.bg[1]), int32(p.bg[2]), int32(p.bg[3])}
		binary.Write(&out, binary.LittleEndian, hdr)
		binary.Write(&out, binary.LittleEndian, p.target)
		out.Write(p.mask)
		name := fmt.Sprintf("alpha_test.prepared.%d.bin", maxRes)
		if err := os.WriteFile(filepath.Join(dataDir, name), out.Bytes(), 0o644); err != nil {
			panic(err)
		}
	}
	// json.MarshalIndent of a small geometry, as output.SaveGeometry writes it.
	type shape struct {
		Type  int       `json:"type"`
		Data  []float64 `json:"data"`
		Color []int     `json:"color"`
		Score float64   `json:"score"`
	}
	type geometry struct {
		Shapes []shape `json:"shapes"`
	}
	g := geometry{Shapes: []shape{
		{Type: 1, Data: []float64{0, 0, 1200, 800}, Color: []int{12, 34, 56, 0}, Score: 0.123457},
		{Type: 16, Data: []float64{600, 400, float64(snapToValidRX(150)), float64(snapToValidRX(33.3)), 45}, Color: []int{255, 0, 128, 200}, Score: 0.000012},
		{Type: 16, Data: []float64{0, 799, 0.63, 1.26, 360}, Color: []int{1, 2, 3, 255}, Score: 0},
	}}
	js, err := json.MarshalIndent(g, "", "  ")
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(filepath.Join(dataDir, "sample_geometry.json"), js, 0o644); err != nil {
		panic(err)
	}
	fmt.Println("wrote", filepath.Join(dir, "go_reference.inc"), "and", dataDir)
}

func boolInt(v bool) int32 {
	if v {
		return 1
	}
	return 0
}
